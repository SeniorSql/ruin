const LIST_ID = 'ruCities';

function ensureList() {
  if (document.getElementById(LIST_ID)) return;
  const dl = document.createElement('datalist');
  dl.id = LIST_ID;
  dl.innerHTML = CITIES.map((c) => `<option value="${c}"></option>`).join('');
  document.body.appendChild(dl);
}

function bind(root) {
  root.querySelectorAll?.('input[name="city"]:not([list])').forEach((inp) => {
    inp.setAttribute('list', LIST_ID);
    inp.setAttribute('autocomplete', 'off'); // чтобы подсказки браузера не перекрывали список городов
  });
}

// Подключает список ко всем полям «Город», в том числе появившимся позже (страницы, окна).
export function initCityList() {
  ensureList();
  bind(document);
  new MutationObserver((muts) => {
    for (const m of muts) m.addedNodes.forEach((n) => { if (n.nodeType === 1) { if (n.matches?.('input[name="city"]')) bind(n.parentNode || document); else bind(n); } });
  }).observe(document.body, { childList: true, subtree: true });
}
