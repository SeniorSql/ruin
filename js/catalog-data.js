// Марки категории (по коду); без категории — все марки
export function brandsFor(catCode) {
  if (catCode && BRANDS[catCode]) return Object.keys(BRANDS[catCode]);
  return [...new Set(Object.values(BRANDS).flatMap((b) => Object.keys(b)))].sort((a, b) => a.localeCompare(b, 'ru'));
}
const findBrand = (catCode, brand) => {
  const pool = catCode && BRANDS[catCode] ? [BRANDS[catCode]] : Object.values(BRANDS);
  for (const b of pool) { const k = Object.keys(b).find((x) => low(x) === low(brand)); if (k) return b[k]; }
  return null;
};
// Модели марки в категории
export function modelsFor(catCode, brand) {
  const m = findBrand(catCode, brand);
  return m ? Object.keys(m) : [];
}
// Типовые характеристики модели: { код характеристики: значение } по порядку specCodes
export function specsFor(catCode, brand, model, specCodes) {
  const m = findBrand(catCode, brand);
  if (!m) return null;
  const k = Object.keys(m).find((x) => low(x) === low(model));
  const arr = k ? m[k] : null;
  if (!Array.isArray(arr) || !arr.length) return null;
  const out = {};
  specCodes.forEach((code, i) => { if (arr[i] != null) out[code] = arr[i]; });
  return Object.keys(out).length ? out : null;
}
